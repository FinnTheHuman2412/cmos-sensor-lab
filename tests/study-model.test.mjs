import assert from 'node:assert/strict';
import {baseline,noiseAt,snrCurves,cdsPower,cdsIntegrated} from '../js/study-model.js';
const eps=(actual,expected,tol=1e-8)=>assert.ok(Math.abs(actual-expected)<=tol,`Expected ${expected}, got ${actual}`);
const b=noiseAt(400,baseline);
eps(b.lsbElectrons,9.765625);
eps(b.quant,9.765625/Math.sqrt(12));
eps(b.shot,20);
eps(b.prnu,4.8);
eps(b.shotSnr,10*Math.log10(400));
eps(b.saturation,10000);
assert.ok(b.snr<b.shotSnr);
const dark=noiseAt(400,{...baseline,dark:100});
eps(dark.dark,10);
assert.ok(dark.snr<b.snr);
assert.ok(noiseAt(400,{...baseline,bits:12}).quant<b.quant);
const curve=snrCurves(baseline);
assert.equal(curve.length,260);
assert.ok(curve.every(x=>Number.isFinite(x.snr)));
eps(cdsPower(0,10),0);
eps(cdsPower(100000,10),0,1e-22);
eps(cdsPower(50000,10),4);
const a=cdsIntegrated(10,100000),c=cdsIntegrated(20,100000);
assert.ok(a.variance>0&&a.referenceVariance>0&&Number.isFinite(a.ratio));
assert.ok(c.variance>0);
console.log('SNR exercise baseline and CDS response model checks passed');
